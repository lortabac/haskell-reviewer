-- | A plain text dump of a 'ModuleIndex', for golden tests. One line
-- per fact, two spaces per level.
module ModulesDump (dumpModules) where

import Data.Foldable (toList)
import Data.Text (Text)
import Data.Text qualified as Text
import HaskellReviewer.Core.Modules
  ( ComponentModules (..),
    GeneratedFile (..),
    HaskellFile (..),
    Literate (..),
    LooseFile (..),
    ModuleEntry (..),
    ModuleId (..),
    ModuleIndex (..),
    ModuleRole (..),
    ModuleSource (..),
    NoSourceReason (..),
    Notice (..),
    OtherFile (..),
    PackageModules (..),
    PreprocessedFile (..),
    moduleRef,
    renderPreprocessor,
  )
import HaskellReviewer.Core.Project
  ( BrokenPackage (..),
    ModuleName (..),
    PackageName (..),
    renderCabalProblem,
    renderComponentName,
    renderProjectWarning,
  )
import HaskellReviewer.Core.RelPath (relDirText, relPathText)

-- | Modules show as @Name [ref] role: source@.
dumpModules :: ModuleIndex -> Text
dumpModules idx =
  Text.unlines $
    map notice idx.notices
      <> concatMap package idx.packages
      <> [ "broken: " <> relPathText b.cabalFile <> ": " <> renderCabalProblem b.problem
         | b <- idx.broken
         ]
      <> map other idx.other
      <> ["warning: " <> renderProjectWarning w | w <- idx.warnings]
  where
    notice = \case
      StackNotice -> "notice: stack"
      ImplicitNotice -> "notice: implicit"
      HpackNotice ds ->
        "notice: hpack: " <> Text.intercalate ", " (map relDirText (toList ds))
    package p =
      let PackageName n = p.name
       in ("package " <> n <> " " <> p.version <> " (" <> relPathText p.cabalFile <> ")")
            : concatMap (component p.name) p.components
    component pkg c =
      ("  " <> renderComponentName c.name <> notBuildable c.buildable)
        : map (entry pkg c.name) c.modules
    entry pkg comp m =
      let ModuleName n = m.name
       in "    "
            <> n
            <> " ["
            <> moduleRef idx (ComponentModule pkg comp m.name)
            <> "] "
            <> role m.role
            <> ": "
            <> source m.source
    role = \case
      RoleExposed -> "exposed"
      RoleOther -> "other"
      RoleSignature -> "signature"
      RoleTestModule -> "test-module"
      RoleMain -> "main"
    source = \case
      HaskellSource f -> relPathText f.path <> literate f.literate
      GeneratedSource f ->
        "generated by " <> renderPreprocessor f.tool <> ": " <> relPathText f.path
      PreprocessedSource f -> "preprocessed by " <> f.tool <> ": " <> relPathText f.path
      NoSource r -> "no source (" <> reason r <> ")"
    notBuildable b = if b then "" else " (not buildable)"
    literate = \case
      NotLiterate -> ""
      BirdOrLatex -> " (literate)"
      MarkdownUnlit -> " (markdown-unlit)"
    reason = \case
      Autogen -> "autogen"
      Missing -> "missing"
      Outside _ -> "outside"
      SymlinkSource p -> "symlink " <> relPathText p
    other = \case
      OtherModule f ->
        "other: "
          <> relPathText f.path
          <> " ["
          <> moduleRef idx (LooseModule f.path)
          <> "]"
      BootFile p -> "other: " <> relPathText p <> " (boot)"
